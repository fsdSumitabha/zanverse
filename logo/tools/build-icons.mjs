// Writes every icon file for Android, iOS, Google Play, Windows and the web app, plus the brand-kit SVGs and
// src/components/ui/ZanMark.tsx, from the rebuilt ZAN mark in logo/tools/zan-mark.json. logo/README.md lists the
// outputs and explains each design choice.
//
// Run from the repo root:
//   npm install --no-save @resvg/resvg-js@2.6.2 pngjs@7.0.0
//   node logo/tools/build-icons.mjs
import fs from "node:fs"
import path from "node:path"
import { Resvg } from "@resvg/resvg-js"
import { PNG } from "pngjs"

const REPO = path.resolve(import.meta.dirname, "../..")
const RES = path.join(REPO, "android/app/src/main/res")
const XCASSETS = path.join(REPO, "ios/zanverse/Images.xcassets")
const KIT = path.join(REPO, "logo")
const GEOMETRY = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, "zan-mark.json"), "utf8"))

// 1. Design decisions.
const BG = "#F1F3FF" // icon background: Material 3 (2025 colour spec) tone 96 of the brand navy
const SPLASH_BG = { light: "#FAFAFA", dark: "#0A0A0A" } // neutral-50 / neutral-950, as SplashView
const ADAPTIVE_MARK_DP = 46 // on the 108 dp adaptive canvas: the square's corners stay inside the 66 dp safe circle
const RATIO = ADAPTIVE_MARK_DP / 72 // mark / visible icon, reused by every flat icon
const SPLASH_MARK_DP = 128 // on the 288 dp splash canvas, inside its 192 dp circle
const NOTIFICATION_GLYPH_DP = 20 // on the 24 dp status-bar canvas
const GENERATED = "Generated by logo/tools/build-icons.mjs from logo/tools/zan-mark.json. Regenerate; do not edit."

// The logo's colours, measured from logo/zan_logo_square.png and flattened. "dark" is for dark backgrounds: the web's
// dark-mode logo colour for the shards. "gray" is the iOS tinted icon: luminance only.
const PALETTES = {
    color: { navy: "#1D3158", patch: "#3D5383", red: "#BE3E3F", orange: "#CB833B" },
    dark: { navy: "#C8D6E5", patch: "#EDF2F8", red: "#BE3E3F", orange: "#CB833B" },
    gray: { navy: "#FFFFFF", patch: "#BDBDBD", red: "#DCDCDC", orange: "#A6A6A6" },
}
const LAYERS = ["navy", "patch", "red", "orange"] // back to front

const written = []

function write(file, data) {
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.writeFileSync(file, data)
    written.push(path.relative(REPO, file).replaceAll("\\", "/"))
}

// 2. SVG.
function fmt(n, digits = 2) {
    const s = n.toFixed(digits).replace(/\.?0+$/, "")
    return s === "-0" ? "0" : s
}

/** Path data for a list of outlines, mapped from mark units into a box at (x, y) of side `size`. */
function pathData(polys, x = 0, y = 0, size = 100) {
    const k = size / 100
    return polys
        .map((p) => {
            const pts = p.map(([u, v]) => `${fmt(x + u * k)} ${fmt(y + v * k)}`)
            return `M${pts[0]}L${pts.slice(1).join(" ")}Z`
        })
        .join("")
}

/** The full mark blurs below about 30 px and its cracks vanish below about 56 px, so small renders use simpler cuts. */
function geometryFor(markPx) {
    if (markPx < 30) return "tiny"
    if (markPx < 56) return "glyph"
    return "mark"
}

function markElements({ geometry, palette, x, y, size }) {
    const g = GEOMETRY[geometry]
    if (palette.mono) return `<path fill="${palette.mono}" d="${pathData([...g.navy, ...g.red], x, y, size)}"/>`
    return LAYERS.filter((layer) => g[layer].length)
        .map((layer) => `<path fill="${PALETTES[palette][layer]}" d="${pathData(g[layer], x, y, size)}"/>`)
        .join("")
}

function mark({ w, h = w, size, palette = "color", geometry = geometryFor(size) }) {
    return markElements({ geometry, palette, x: (w - size) / 2, y: (h - size) / 2, size })
}

function svgDoc(width, height, body) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${body}</svg>`
}

/** Full-bleed square, background and mark. The platform masks it. */
function squareIcon(px, { ratio = RATIO } = {}) {
    return svgDoc(px, px, `<rect width="${px}" height="${px}" fill="${BG}"/>${mark({ w: px, size: px * ratio })}`)
}

/**
 * The app icon as a rounded plate on transparency, for places that show an icon unmasked (Windows, the PWA "any"
 * icons). Small plates give the mark more of their area, or a 16 px icon would carry a 9 px mark.
 */
function plateIcon(px) {
    const inset = Math.max(1, Math.round(px * 0.04))
    const plate = px - 2 * inset
    const ratio = px <= 24 ? 0.82 : px <= 48 ? 0.74 : RATIO
    const shape = `<rect x="${inset}" y="${inset}" width="${plate}" height="${plate}" rx="${fmt(plate * 0.22)}" fill="${BG}"/>`
    return svgDoc(px, px, shape + mark({ w: px, size: plate * ratio }))
}

function bareMark(w, h, { ratio, palette = "color" }) {
    return svgDoc(w, h, mark({ w, h, size: Math.min(w, h) * ratio, palette }))
}

// 3. PNG and ICO.
function rendered(svg) {
    return new Resvg(svg, { fitTo: { mode: "original" } }).render()
}

function pngRGBA(svg) {
    return rendered(svg).asPng()
}

// The App Store rejects an icon with an alpha channel, and the iOS tinted icon is a grayscale image. Both are opaque,
// so resvg's premultiplied pixels equal the straight ones. colorType: 2 = RGB, 0 = grayscale.
function pngOpaque(svg, colorType) {
    const r = rendered(svg)
    const png = new PNG({ width: r.width, height: r.height })
    png.data = Buffer.from(r.pixels)
    return PNG.sync.write(png, { colorType, inputColorType: 6, inputHasAlpha: true })
}

/** An ICO of PNG images (Windows Vista and later, every browser). */
function ico(images) {
    const header = Buffer.alloc(6 + 16 * images.length)
    header.writeUInt16LE(1, 2)
    header.writeUInt16LE(images.length, 4)
    let offset = header.length
    images.forEach(({ size, png }, i) => {
        const at = 6 + 16 * i
        header.writeUInt8(size >= 256 ? 0 : size, at)
        header.writeUInt8(size >= 256 ? 0 : size, at + 1)
        header.writeUInt16LE(1, at + 4)
        header.writeUInt16LE(32, at + 6)
        header.writeUInt32LE(png.length, at + 8)
        header.writeUInt32LE(offset, at + 12)
        offset += png.length
    })
    return Buffer.concat([header, ...images.map((image) => image.png)])
}

// 4. Android.
function vectorDrawable({ dp, x, size, geometry, palette, comment }) {
    const g = GEOMETRY[geometry]
    const layers = palette.mono
        ? [{ color: palette.mono, d: pathData([...g.navy, ...g.red]) }]
        : LAYERS.filter((l) => g[l].length).map((l) => ({ color: PALETTES[palette][l], d: pathData(g[l]) }))
    const paths = layers
        .map(({ color, d }) => `        <path\n            android:fillColor="${color}"\n            android:pathData="${d}" />`)
        .join("\n")
    return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment}
     ${GENERATED} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${dp}dp"
    android:height="${dp}dp"
    android:viewportWidth="${dp}"
    android:viewportHeight="${dp}">
    <group
        android:translateX="${fmt(x)}"
        android:translateY="${fmt(x)}"
        android:scaleX="${fmt(size / 100, 4)}"
        android:scaleY="${fmt(size / 100, 4)}">
${paths}
    </group>
</vector>
`
}

function buildAndroid() {
    const o = (108 - ADAPTIVE_MARK_DP) / 2
    write(path.join(RES, "drawable/ic_launcher_foreground.xml"), vectorDrawable({
        dp: 108, x: o, size: ADAPTIVE_MARK_DP, geometry: "mark", palette: "color",
        comment: "Adaptive launcher icon, foreground: the ZAN mark, 46 dp inside the 66 dp safe zone of the 108 dp canvas.",
    }))
    write(path.join(RES, "drawable/ic_launcher_monochrome.xml"), vectorDrawable({
        dp: 108, x: o, size: ADAPTIVE_MARK_DP, geometry: "mark", palette: { mono: "#FF000000" },
        comment: "Themed launcher icon (Android 13+): the mark's silhouette. The system reads only its alpha and tints it.",
    }))
    write(path.join(RES, "drawable/ic_notification.xml"), vectorDrawable({
        dp: 24, x: (24 - NOTIFICATION_GLYPH_DP) / 2, size: NOTIFICATION_GLYPH_DP, geometry: "glyph", palette: { mono: "#FFFFFFFF" },
        comment: "Status-bar icon: the mark in white, with wider cracks that stay visible at 24 dp. Android reads only its alpha.",
    }))
    const so = (288 - SPLASH_MARK_DP) / 2
    write(path.join(RES, "drawable/splash_icon.xml"), vectorDrawable({
        dp: 288, x: so, size: SPLASH_MARK_DP, geometry: "mark", palette: "color",
        comment: "Android 12+ splash icon: the mark at 128 dp, inside the 192 dp circle of the 288 dp canvas. SplashView draws it at the same size.",
    }))
    write(path.join(RES, "drawable-night/splash_icon.xml"), vectorDrawable({
        dp: 288, x: so, size: SPLASH_MARK_DP, geometry: "mark", palette: "dark",
        comment: "Android 12+ splash icon in dark mode: the mark in the web's dark-mode logo colours.",
    }))

    const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Android 8+ launcher icon. Background: a flat colour. Foreground: the ZAN mark. Monochrome: the themed icon (Android 13+).
     ${GENERATED} -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`
    write(path.join(RES, "mipmap-anydpi-v26/ic_launcher.xml"), adaptive)
    write(path.join(RES, "mipmap-anydpi-v26/ic_launcher_round.xml"), adaptive)

    // Android 7 (API 24-25) has no adaptive icons: 48 dp bitmaps, a rounded square and a circle, 2 dp margin.
    for (const [bucket, scale] of Object.entries({ mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 })) {
        const px = 48 * scale
        const plate = 44 * scale
        const m = mark({ w: px, size: plate * RATIO })
        const square = `<rect x="${2 * scale}" y="${2 * scale}" width="${plate}" height="${plate}" rx="${8 * scale}" fill="${BG}"/>`
        const round = `<circle cx="${px / 2}" cy="${px / 2}" r="${plate / 2}" fill="${BG}"/>`
        write(path.join(RES, `mipmap-${bucket}/ic_launcher.png`), pngRGBA(svgDoc(px, px, square + m)))
        write(path.join(RES, `mipmap-${bucket}/ic_launcher_round.png`), pngRGBA(svgDoc(px, px, round + m)))
    }
}

// 5. iOS: the app icon (default, dark, tinted), the launch screen's logo and background, and Icon Composer layers.
const XCODE_INFO = { author: "xcode", version: 1 }
const DARK = [{ appearance: "luminosity", value: "dark" }]

function xcodeJson(obj) {
    return JSON.stringify(obj, null, 2).replace(/": /g, '" : ') + "\n"
}

function buildIos() {
    const dir = path.join(XCASSETS, "AppIcon.appiconset")
    const m = 1024 * RATIO
    write(path.join(dir, "AppIcon-1024.png"), pngOpaque(squareIcon(1024), 2))
    // Apple: the dark icon has a transparent background, so the system's dark background shows through.
    write(path.join(dir, "AppIcon-1024-dark.png"), pngRGBA(svgDoc(1024, 1024, mark({ w: 1024, size: m, palette: "dark" }))))
    // Apple: the tinted icon is a grayscale image. The system tints it by luminance.
    write(path.join(dir, "AppIcon-1024-tinted.png"), pngOpaque(svgDoc(1024, 1024, `<rect width="1024" height="1024" fill="#000000"/>${mark({ w: 1024, size: m, palette: "gray" })}`), 0))
    write(path.join(dir, "Contents.json"), xcodeJson({
        images: [
            { filename: "AppIcon-1024.png", idiom: "universal", platform: "ios", size: "1024x1024" },
            { appearances: DARK, filename: "AppIcon-1024-dark.png", idiom: "universal", platform: "ios", size: "1024x1024" },
            { appearances: [{ appearance: "luminosity", value: "tinted" }], filename: "AppIcon-1024-tinted.png", idiom: "universal", platform: "ios", size: "1024x1024" },
        ],
        info: XCODE_INFO,
    }))

    const logo = path.join(XCASSETS, "LaunchLogo.imageset")
    const images = []
    for (const scale of [1, 2, 3]) {
        const px = SPLASH_MARK_DP * scale
        const suffix = scale === 1 ? "" : `@${scale}x`
        write(path.join(logo, `LaunchLogo${suffix}.png`), pngRGBA(bareMark(px, px, { ratio: 1 })))
        write(path.join(logo, `LaunchLogo-dark${suffix}.png`), pngRGBA(bareMark(px, px, { ratio: 1, palette: "dark" })))
        images.push({ filename: `LaunchLogo${suffix}.png`, idiom: "universal", scale: `${scale}x` })
        images.push({ appearances: DARK, filename: `LaunchLogo-dark${suffix}.png`, idiom: "universal", scale: `${scale}x` })
    }
    write(path.join(logo, "Contents.json"), xcodeJson({ images, info: XCODE_INFO }))

    const component = (hex) => `0x${hex}`
    const color = (v) => ({
        "color-space": "srgb",
        components: { alpha: "1.000", blue: component(v.slice(5, 7)), green: component(v.slice(3, 5)), red: component(v.slice(1, 3)) },
    })
    write(path.join(XCASSETS, "LaunchBackground.colorset/Contents.json"), xcodeJson({
        colors: [
            { color: color(SPLASH_BG.light), idiom: "universal" },
            { appearances: DARK, color: color(SPLASH_BG.dark), idiom: "universal" },
        ],
        info: XCODE_INFO,
    }))

    // Icon Composer (Liquid Glass, iOS 26+): one SVG per colour on the 1024 canvas, no background, back to front.
    const o = (1024 - m) / 2
    const names = { navy: "1-shards", patch: "2-highlights", red: "3-triangle", orange: "4-tip" }
    for (const layer of LAYERS) {
        const d = pathData(GEOMETRY.mark[layer], o, o, m)
        write(path.join(KIT, `ios/icon-composer/${names[layer]}.svg`), svgDoc(1024, 1024, `<path fill="${PALETTES.color[layer]}" d="${d}"/>`) + "\n")
    }
}

// 6. Google Play: the 512 px listing icon and a 1024 x 500 feature graphic.
function buildPlay() {
    write(path.join(KIT, "play-store/icon-512.png"), pngRGBA(squareIcon(512)))
    // The dark mark on the brand navy, over a soft 12-lobe "cookie" from the Material 3 Expressive shape set.
    const W = 1024, H = 500
    const pts = []
    for (let i = 0; i < 720; i++) {
        const t = (i / 720) * Math.PI * 2
        const r = 205 * (1 + 0.045 * Math.cos(12 * t))
        pts.push(`${fmt(W / 2 + r * Math.cos(t))} ${fmt(H / 2 + r * Math.sin(t))}`)
    }
    const cookie = `<path fill="#25406E" d="M${pts[0]}L${pts.slice(1).join(" ")}Z"/>`
    const body = `<rect width="${W}" height="${H}" fill="#1D3158"/>${cookie}${mark({ w: W, h: H, size: 250, palette: "dark" })}`
    write(path.join(KIT, "play-store/feature-graphic-1024x500.png"), pngOpaque(svgDoc(W, H, body), 2))
}

// 7. Windows: an ICO, and the MSIX visual assets. Windows uses the web app today (docs/WINDOWS.md).
function buildWindows() {
    const icoSizes = [16, 20, 24, 30, 32, 36, 40, 48, 60, 64, 72, 80, 96, 128, 256]
    write(path.join(KIT, "windows/zan.ico"), ico(icoSizes.map((s) => ({ size: s, png: pngRGBA(plateIcon(s)) }))))

    const dir = path.join(KIT, "windows/msix")
    for (const [name, f] of Object.entries({ 100: 1, 125: 1.25, 150: 1.5, 200: 2, 400: 4 })) {
        const px = (base) => Math.round(base * f)
        write(path.join(dir, `Square44x44Logo.scale-${name}.png`), pngRGBA(plateIcon(px(44))))
        write(path.join(dir, `StoreLogo.scale-${name}.png`), pngRGBA(squareIcon(px(50))))
        write(path.join(dir, `Square71x71Logo.scale-${name}.png`), pngRGBA(squareIcon(px(71), { ratio: 0.56 })))
        write(path.join(dir, `Square150x150Logo.scale-${name}.png`), pngRGBA(squareIcon(px(150), { ratio: 0.46 })))
        write(path.join(dir, `Square310x310Logo.scale-${name}.png`), pngRGBA(squareIcon(px(310), { ratio: 0.4 })))
        const [ww, wh] = [px(310), px(150)]
        write(path.join(dir, `Wide310x150Logo.scale-${name}.png`), pngRGBA(svgDoc(ww, wh, `<rect width="${ww}" height="${wh}" fill="${BG}"/>${mark({ w: ww, h: wh, size: wh * 0.46 })}`)))
        const [sw, sh] = [px(620), px(300)]
        write(path.join(dir, `SplashScreen.scale-${name}.png`), pngRGBA(svgDoc(sw, sh, mark({ w: sw, h: sh, size: sh * 0.5 }))))
    }
    for (const s of [16, 20, 24, 30, 32, 36, 40, 48, 60, 64, 72, 80, 96, 256]) {
        write(path.join(dir, `Square44x44Logo.targetsize-${s}.png`), pngRGBA(plateIcon(s)))
        write(path.join(dir, `Square44x44Logo.targetsize-${s}_altform-unplated.png`), pngRGBA(bareMark(s, s, { ratio: 0.88, palette: "dark" })))
        write(path.join(dir, `Square44x44Logo.targetsize-${s}_altform-lightunplated.png`), pngRGBA(bareMark(s, s, { ratio: 0.88 })))
    }
}

// 8. The web app, the Windows client today: favicons, PWA icons and a manifest snippet.
function buildWeb() {
    const dir = path.join(KIT, "web")
    write(path.join(dir, "favicon.ico"), ico([16, 32, 48].map((s) => ({ size: s, png: pngRGBA(plateIcon(s)) }))))
    const g = GEOMETRY.tiny
    const css = `@media (prefers-color-scheme: dark){.n{fill:${PALETTES.dark.navy}}}`
    write(path.join(dir, "icon.svg"), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><style>${css}</style><path class="n" fill="${PALETTES.color.navy}" d="${pathData(g.navy)}"/><path fill="${PALETTES.color.red}" d="${pathData(g.red)}"/><path fill="${PALETTES.color.orange}" d="${pathData(g.orange)}"/></svg>\n`)
    write(path.join(dir, "apple-touch-icon.png"), pngOpaque(squareIcon(180), 2))
    for (const s of [192, 512]) {
        write(path.join(dir, `icon-${s}.png`), pngRGBA(plateIcon(s)))
        write(path.join(dir, `icon-maskable-${s}.png`), pngRGBA(squareIcon(s, { ratio: 0.5 })))
    }
    write(path.join(dir, "icon-monochrome-512.png"), pngRGBA(bareMark(512, 512, { ratio: 0.8, palette: { mono: "#FFFFFF" } })))
    const icons = [
        { src: "/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
        { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
        { src: "/icon-maskable-192.png", sizes: "192x192", type: "image/png", purpose: "maskable" },
        { src: "/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
        { src: "/icon-monochrome-512.png", sizes: "512x512", type: "image/png", purpose: "monochrome" },
    ]
    write(path.join(dir, "manifest-icons.json"), JSON.stringify({ icons }, null, 4) + "\n")
}

// 9. Source SVGs for designers.
function buildKitSvgs() {
    const dir = path.join(KIT, "svg")
    const one = (geometry, palette) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">${markElements({ geometry, palette, x: 0, y: 0, size: 100 })}</svg>\n`
    write(path.join(dir, "zan-mark.svg"), one("mark", "color"))
    write(path.join(dir, "zan-mark-dark.svg"), one("mark", "dark"))
    write(path.join(dir, "zan-mark-mono.svg"), one("mark", { mono: "#000000" }))
    write(path.join(dir, "zan-mark-glyph.svg"), one("glyph", "color"))
    write(path.join(dir, "zan-mark-tiny.svg"), one("tiny", "color"))
    write(path.join(dir, "zan-app-icon.svg"), squareIcon(1024) + "\n")
}

// 10. The React Native component, from the same outlines.
function buildComponent() {
    const g = GEOMETRY.mark
    const lines = (layer) => g[layer].map((p) => `    "${pathData([p])}",`).join("\n")
    const tone = (p) => `{ ${Object.entries(p).map(([k, v]) => `${k}: "${v}"`).join(", ")} }`
    const ts = `import Svg, { Path } from "react-native-svg"

// The ZAN mark, rebuilt as vectors from logo/zan_logo_square.png (logo/README.md). One subpath per shape, in mark
// units: the mark's square runs from 0 to 100. Generated by logo/tools/build-icons.mjs: regenerate, do not edit.
const SHARDS = [
${lines("navy")}
].join("")
const HIGHLIGHTS = [
${lines("patch")}
].join("")
const TRIANGLE = [
${lines("red")}
].join("")
const TIP = [
${lines("orange")}
].join("")

/** The logo's colours, flattened. Dark is for a dark background: the web's dark-mode logo colour for the shards. */
const TONES = {
    light: ${tone(PALETTES.color)},
    dark: ${tone(PALETTES.dark)},
} as const

interface ZanMarkProps {
    /** Width and height, in dp. */
    size: number
    /** "dark" on a dark background. */
    tone?: keyof typeof TONES
}

/** The ZAN mark, square. Decorative: the screen that shows it also names the app in text. */
export default function ZanMark({ size, tone = "light" }: ZanMarkProps) {
    const colors = TONES[tone]

    return (
        <Svg width={size} height={size} viewBox="0 0 100 100">
            <Path fill={colors.navy} d={SHARDS} />
            <Path fill={colors.patch} d={HIGHLIGHTS} />
            <Path fill={colors.red} d={TRIANGLE} />
            <Path fill={colors.orange} d={TIP} />
        </Svg>
    )
}
`
    write(path.join(REPO, "src/components/ui/ZanMark.tsx"), ts)
}

